func writeTestFile(t *testing.T, root, rel, content string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", rel, err)
	}
	if err := os.WriteFile(full, []byte(content), 0o600); err != nil {
		t.Fatalf("write %s: %v", rel, err)
	}
}

func assertViolationsContainRule(t *testing.T, root string, opts checkOptions, wantRule string) {
	t.Helper()
	opts.rootDir = root
	violations, err := runChecks(opts)
	if err != nil {
		t.Fatalf("unexpected execution error: %v", err)
	}
	for _, v := range violations {
		if v.Rule == wantRule {
			return
		}
	}
	t.Fatalf("expected violation rule %q, got %v", wantRule, violations)
}

func TestFloorGuardRejectsAllNegativeFixtures(t *testing.T) {
	cases := []struct {
		name     string
		relPath  string
		content  string
		wantRule string
	}{
		{
			name:     "ts-ignore directive",
			relPath:  "web/console/src/bad.ts",
			content:  "// @" + "ts-ignore\nconst x: number = 'bad' as unknown as number;\n",
			wantRule: "no-ts-ignore",
		},
		{
			name:     "eslint disable directive",
			relPath:  "web/console/src/bad.tsx",
			content:  "/* eslint-" + "disable */\nexport const x = 1;\n",
			wantRule: "no-eslint-biome-disable",
		},
		{
			name:     "nolint gosec directive",
			relPath:  "internal/pkg/unsafe.go",
			content:  "package pkg\nfunc f() {} // " + "nolint:errcheck,gosec\n",
			wantRule: "no-gosec-nolint",
		},
		{
			name:     "bare nolint directive",
			relPath:  "internal/pkg/unsafe2.go",
			content:  "package pkg\nfunc f() {} // " + "nolint\n",
			wantRule: "no-gosec-nolint",
		},
		{
			name:     "gitleaks allow directive",
			relPath:  "internal/pkg/leak.go",
			content:  "package pkg\nvar k = \"x\" // gitleaks:" + "allow\n",
			wantRule: "no-sec-allow",
		},
		{
			name:     "unticketed t.Skip call",
			relPath:  "internal/pkg/flaky_test.go",
			content:  "package pkg\nimport \"testing\"\nfunc TestX(t *testing.T) { t." + "Skip(\"later\") }\n",
			wantRule: "no-test-skip",
		},
		{
			name:     "benchmark b.SkipNow call",
			relPath:  "internal/pkg/bench_test.go",
			content:  "package pkg\nimport \"testing\"\nfunc BenchmarkX(b *testing.B) { b." + "SkipNow() }\n",
			wantRule: "no-test-skip",
		},
		{
			name:     "http.DefaultClient usage",
			relPath:  "internal/security/vault/client.go",
			content:  "package vault\nimport \"net/http\"\nfunc f() any { return http.Default" + "Client }\n",
			wantRule: "ban-http-default-client",
		},
		{
			name:     "aliased net/http Get call",
			relPath:  "cmd/tanpopo/net.go",
			content:  "package main\nimport h \"net/http\"\nfunc g() { _, _ = h.Ge" + "t(\"http://example.com\") }\n",
			wantRule: "ban-http-default-client",
		},
		{
			name:     "dot import net/http",
			relPath:  "internal/security/vault/dothttp.go",
			content:  "package vault\nimport . \"net/http\"\nfunc g() { _, _ = Get(\"http://169.254.169.254\") }\n",
			wantRule: "ban-http-dot-import",
		},
		{
			name:     "http.Client literal without Transport",
			relPath:  "internal/security/vault/emptyclient.go",
			content:  "package vault\nimport \"net/http\"\nfunc c() *http.Client { return &http.Client{} }\n",
			wantRule: "ban-http-client-nil-transport",
		},
		{
			name:     "multiline raw div tag in console src (LF)",
			relPath:  "web/console/src/Card.tsx",
			content:  "export function Bad() { return (\n  <" + "div\n    id=\"x\">raw</" + "div>\n); }\n",
			wantRule: "no-raw-div-span",
		},
		{
			name:     "multiline empty catch block",
			relPath:  "web/console/src/err.mts",
			content:  "export function f() {\n  try {\n    return 1;\n  } ca" + "tch (e) {\n  }\n}\n",
			wantRule: "no-stubs-or-empty-catch",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := seedCleanRepo(t)
			writeTestFile(t, root, tc.relPath, tc.content)
			assertViolationsContainRule(t, root, checkOptions{floorGuard: true}, tc.wantRule)
		})
	}
}

func TestDAGRejectsCyclesLayerInversionsAndBannedImports(t *testing.T) {
	t.Run("rejects layer inversion storage importing security", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/storage/sqlite/bad.go",
			"package sqlite\nimport _ \"github.com/nguywnben/tanpopo/internal/security/vault\"\n")
		assertViolationsContainRule(t, root, checkOptions{dag: true}, "dag-layer-violation")
	})

	t.Run("rejects import cycle", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/iam/iam.go",
			"package iam\nimport _ \"github.com/nguywnben/tanpopo/internal/policy\"\n")
		writeTestFile(t, root, "internal/policy/policy.go",
			"package policy\nimport _ \"github.com/nguywnben/tanpopo/internal/iam\"\n")
		assertViolationsContainRule(t, root, checkOptions{dag: true}, "import-cycle")
	})

	t.Run("rejects unregistered internal package", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/rogue/x.go", "package rogue\n")
		assertViolationsContainRule(t, root, checkOptions{dag: true}, "unregistered-internal-package")
	})

	t.Run("rejects importing tools/spikes module", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/ingress/bad.go",
			"package ingress\nimport _ \"github.com/nguywnben/tanpopo-spikes\"\n")
		assertViolationsContainRule(t, root, checkOptions{dag: true}, "ban-tools-spikes-import")
	})

	t.Run("rejects non-test production import of internal/testkit", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/testkit/fake.go", "package testkit\n")
		writeTestFile(t, root, "internal/admin/bad.go",
			"package admin\nimport _ \"github.com/nguywnben/tanpopo/internal/testkit\"\n")
		assertViolationsContainRule(t, root, checkOptions{dag: true}, "ban-prod-testkit-import")
	})

	t.Run("allows test files to import internal/testkit", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "internal/testkit/fake.go", "package testkit\n")
		writeTestFile(t, root, "internal/admin/ok_test.go",
			"package admin\nimport _ \"github.com/nguywnben/tanpopo/internal/testkit\"\n")
		v, err := runChecks(checkOptions{rootDir: root, dag: true})
		if err != nil || len(v) != 0 {
			t.Fatalf("expected 0 DAG violations for _test.go importing testkit, got err=%v v=%v", err, v)
		}
	})
}

func TestLicenseLockfilesUILayoutAndCanary(t *testing.T) {
	t.Run("rejects GPL dependency in package-lock", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "web/console/package-lock.json",
			`{"packages":{"":{"license":"Apache-2.0"},"node_modules/evil":{"license":"GPL-3.0"}}}`)
		assertViolationsContainRule(t, root, checkOptions{license: true}, "no-copyleft-dependency")
	})

	t.Run("rejects competing yarn.lock", func(t *testing.T) {
		root := seedCleanRepo(t)
		writeTestFile(t, root, "web/console/yarn.lock", "# yarn lockfile\n")
		assertViolationsContainRule(t, root, checkOptions{lockfiles: true}, "single-npm-lockfile")
	})

	t.Run("rejects :root override, CRLF in astryx-themes.js and Vietnamese UI copy", func(t *testing.T) {
		root := seedCleanRepo(t)
		crlfTheme := "/**\r\n * @generated by `astryx theme` — do not edit manually.\r\n * " + expectedThemeRecord + "\r\n */\r\nexport const defaultThemeSlug = \"neutral\";\r\n"
		writeTestFile(t, root, "web/console/astryx-themes.js", crlfTheme)
		assertViolationsContainRule(t, root, checkOptions{uiLayout: true}, "theme-module-must-be-lf")

		writeTestFile(t, root, "web/console/astryx-themes.js", ":root { --foo: #fff; }\n")
		assertViolationsContainRule(t, root, checkOptions{uiLayout: true}, "astryx-theme-unmodified-neutral")

		writeTestFile(t, root, "web/console/src/App.tsx", "export const title = 'Xin ch" + "\u00e0" + "o';\n")
		assertViolationsContainRule(t, root, checkOptions{uiLayout: true}, "english-ui-copy")
	})

	t.Run("redacts canary secret without printing raw value", func(t *testing.T) {
		root := seedCleanRepo(t)
		secretVal := "CANARY_FORBIDDEN_" + "CI_KEY"
		writeTestFile(t, root, "cmd/tanpopo/leak.go", "package main\nvar s = \""+secretVal+"\"\n")

		var out, errBuf bytes.Buffer
		code := runCLI([]string{"--root", root, "--canary"}, &out, &errBuf)
		if code != 1 {
			t.Fatalf("expected exit code 1 on canary leak, got %d", code)
		}
		if strings.Contains(errBuf.String(), secretVal) {
			t.Fatalf("stderr leaked unredacted canary value: %q", errBuf.String())
		}
		if !strings.Contains(errBuf.String(), "canary-token-leak") {
			t.Fatalf("expected canary-token-leak rule in stderr, got: %q", errBuf.String())
		}

		// Also reject sk-tp-canary-* prefix mandated by CONSTRAINTS.md without echoing value!
		skCanary := "sk-tp-" + "canary-DO-NOT-LEAK-1234"
		writeTestFile(t, root, "web/console/vite.config.ts", "export const key = \""+skCanary+"\";\n")
		out.Reset()
		errBuf.Reset()
		code = runCLI([]string{"--root", root, "--canary"}, &out, &errBuf)
		if code != 1 || strings.Contains(errBuf.String(), skCanary) || !strings.Contains(errBuf.String(), "secret-material-detected") {
			t.Fatalf("expected redacted secret-material-detected on sk canary leak, got code=%d stderr=%q", code, errBuf.String())
		}
	})
}

